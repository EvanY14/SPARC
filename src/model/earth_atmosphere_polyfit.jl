earth_atmosphere_polyfit_altitude_value(h_m::Real) = h_m
earth_atmosphere_polyfit_altitude_value(h_m::ForwardDiff.Dual) = ForwardDiff.value(h_m)

function earth_atmosphere_polyfit_coefficients(h_m::Real)
    h_value = earth_atmosphere_polyfit_altitude_value(h_m)
    if 0.0 <= h_value < EARTH_ATMOSPHERE_POLYFIT_MAX_M
        idx = clamp(fld(Int(floor(h_value)), Int(EARTH_ATMOSPHERE_POLYFIT_INTERVAL_M)) + 1, 1, length(EARTH_ATMOSPHERE_POLYFIT_COEFFICIENTS))
        return EARTH_ATMOSPHERE_POLYFIT_COEFFICIENTS[idx]
    end
    return EARTH_ATMOSPHERE_HIGH_ALTITUDE_POLYFIT
end

function earth_atmosphere_log_density(h_m)
    h_km = h_m * 1.0e-3
    coeffs = earth_atmosphere_polyfit_coefficients(h_m)
    exponent = zero(h_km)
    for c in coeffs
        exponent = exponent * h_km + c
    end
    return exponent
end

earth_atmosphere_density(h_m) = exp(earth_atmosphere_log_density(h_m))
